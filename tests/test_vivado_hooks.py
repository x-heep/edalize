"""Tests for the pre_build and post_build hooks of the Vivado backend.

The hooks are run by the backend itself, before and after make, like for the
other backends. A pre_build script can therefore generate an input of the
build, e.g. a source file listed in the EDAM. This used to fail with "No rule
to make target", because the hooks were run from the Makefile where pre_build
is only an order-only prerequisite of the first command, so make checked the
inputs of that command before the script had run.
"""

import os
import shutil
import stat

import pytest

from edalize.edatool import get_edatool

pytestmark = pytest.mark.skipif(
    shutil.which("make") is None or os.name == "nt", reason="needs make and sh"
)


@pytest.fixture
def prepend_to_path(monkeypatch):
    """Put a directory first in PATH, for the processes that the test starts.

    make has to find the stand-in for vivado. Setting PATH through monkeypatch
    is not enough: another test (test_xcelium) leaves os.environ out of sync
    with the real environment, which is what subprocesses inherit, so set both.
    """

    def prepend(directory):
        path = f"{directory}{os.pathsep}{os.environ['PATH']}"
        monkeypatch.setenv("PATH", path)
        os.putenv("PATH", path)

    yield prepend

    monkeypatch.undo()
    os.putenv("PATH", os.environ["PATH"])


def script(path, text):
    path.write_text("#!/bin/sh\n" + text)
    path.chmod(path.stat().st_mode | stat.S_IEXEC)
    return ["sh", str(path)]


def make_tool(tmp_path, prepend_to_path, pre_build_ok=True):
    """Return a Vivado backend whose only source is generated by pre_build, and
    the log in which the hooks and a stand-in for vivado record their calls"""
    gen = tmp_path / "gen"
    log = tmp_path / "order.log"

    # A stand-in for vivado that, like the real one, needs the source to exist
    bindir = tmp_path / "bin"
    bindir.mkdir()
    script(
        bindir / "vivado",
        f'[ -f "{gen}/foo.v" ] || {{ echo "foo.v missing" >&2; exit 3; }}\n'
        f'echo vivado >> "{log}"\n'
        f'touch "{tmp_path}/work/hooks.xpr"\n',
    )
    prepend_to_path(bindir)

    pre = script(
        tmp_path / "pre.sh",
        ("" if pre_build_ok else "exit 1\n")
        + f'mkdir -p "{gen}"\necho "module foo; endmodule" > "{gen}/foo.v"\n'
        f'echo pre >> "{log}"\n',
    )
    post = script(tmp_path / "post.sh", f'echo post >> "{log}"\n')

    edam = {
        "name": "hooks",
        "toplevel": "foo",
        "files": [{"name": str(gen / "foo.v"), "file_type": "verilogSource"}],
        "hooks": {
            "pre_build": [{"name": "gen_foo", "cmd": pre, "env": {}}],
            "post_build": [{"name": "post", "cmd": post, "env": {}}],
        },
        "tool_options": {"vivado": {"part": "xc7z020clg400-1"}},
        "parameters": {},
        "version": "0.1.0",
    }
    work_root = tmp_path / "work"
    work_root.mkdir()
    tool = get_edatool("vivado")(edam=edam, work_root=str(work_root), verbose=False)
    tool.configure()
    return tool, work_root, log


def test_pre_build_can_generate_inputs(tmp_path, prepend_to_path):
    tool, work_root, log = make_tool(tmp_path, prepend_to_path)
    tool.build()

    # Each hook ran once, around the two vivado steps (project, then bitstream)
    assert log.read_text().split() == ["pre", "vivado", "vivado", "post"]
    assert (tmp_path / "gen" / "foo.v").exists()


def test_hooks_are_not_also_run_from_the_makefile(tmp_path, prepend_to_path):
    tool, work_root, log = make_tool(tmp_path, prepend_to_path)
    makefile = (work_root / "Makefile").read_text()

    # The scripts would otherwise run a second time, from make
    assert "pre.sh" not in makefile
    assert "post.sh" not in makefile


def test_failing_pre_build_stops_the_build(tmp_path, prepend_to_path):
    tool, work_root, log = make_tool(tmp_path, prepend_to_path, pre_build_ok=False)
    with pytest.raises(RuntimeError):
        tool.build()

    # vivado was never run
    assert not log.exists() or "vivado" not in log.read_text().split()
